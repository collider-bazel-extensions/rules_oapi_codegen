#!/usr/bin/env bash
# Usage: assert_generated.sh <generated.go> <package>
# Checks the file oapi-codegen wrote carries the generated-code marker Go
# tooling looks for, the pinned oapi-codegen module and version, and the
# package clause.
set -euo pipefail

file="$1"
pkg="$2"

fail() { echo "FAIL: $*" >&2; exit 1; }

[[ -s "$file" ]] || fail "$file is empty or missing"
grep -Eq '^// Code generated .* DO NOT EDIT\.$' "$file" \
    || fail "$file lacks a '// Code generated ... DO NOT EDIT.' line"
grep -q 'oapi-codegen/v2 version v2\.8\.0 ' "$file" \
    || fail "$file was not generated by oapi-codegen v2.8.0"
grep -qx "package $pkg" "$file" || fail "$file lacks 'package $pkg'"
echo "PASS: $file"
